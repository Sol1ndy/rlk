"""Compile frame-addressed Minecraft sound layers for Arlecchino and Skirk.

Run: python tools/build_player_audio.py [--catalog <installed sounds.json>]
No recorded/reference audio or additional resource-pack sound files are used.
"""
from pathlib import Path
import argparse
import json
import sys
sys.dont_write_bytecode=True
from player_motion.audio_arle import timeline as arle_timeline
from player_motion.audio_skirk import timeline as skirk_timeline

here=Path(__file__).resolve().parent
pack=here.parent
motion=pack/'data/rlk/function/char/motion'
parser=argparse.ArgumentParser()
parser.add_argument('--catalog',type=Path)
args=parser.parse_args()
catalog=json.loads(args.catalog.read_text(encoding='utf-8')) if args.catalog else None
compiled={}
used=set()
for char, author in (('arle',arle_timeline),('skirk',skirk_timeline)):
    clips=json.loads((here/'player_motion'/f'{char}.json').read_text(encoding='utf-8'))['clips']
    compiled[char]={}
    for name, clip in clips.items():
        layers=author(name,clip)
        if not layers:
            # The existing movement-loop silence remains untouched.
            continue
        hook=f'function rlk:char/motion/audio/{char}/{name}'
        event=(motion/'events'/char/f'{name}.mcfunction').read_text(encoding='utf-8').splitlines()
        if event.count(hook)!=1:
            raise ValueError(f'{char}/{name} needs exactly one existing per-frame audio hook')
        lines=['# Vanilla-only layered combat sound; generated by tools/build_player_audio.py.',
               '# Frame timing follows the animation clock, including attack-speed changes.']
        for layer in layers:
            tick,sound,volume,pitch=(layer[k] for k in ('tick','event','volume','pitch'))
            if not isinstance(tick,int) or not 0<=tick<=clip['length']:
                raise ValueError(f'Audio frame outside clip: {char}/{name}: {tick}')
            if not 0<volume<=1 or not .5<=pitch<=2:
                raise ValueError(f'Unsupported audio layer range: {char}/{name}: {layer}')
            if catalog is not None and sound not in catalog:
                raise ValueError(f'Vanilla sound absent from installed catalog: {sound}')
            used.add(sound)
            lines.append(f'# {layer["layer"]}')
            lines.append(f'execute if score @s pmTick matches {tick} run playsound minecraft:{sound} player @s ~ ~ ~ {volume:g} {pitch:g} 0')
        target=motion/'audio'/char/f'{name}.mcfunction'
        target.write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
        compiled[char][name]={'playback_rate':clip.get('playback_rate',100),
                              'hit_ticks':clip.get('hit_ticks',[]),'layers':layers}
manifest={'source':'Minecraft vanilla events only; no recording assets.',
          'characters':compiled,'sound_events':sorted(used)}
(here/'player_motion/compiled_audio.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'clips':{char:len(clips) for char,clips in compiled.items()},
                  'sound_events':len(used),
                  'layers':sum(len(clip['layers']) for clips in compiled.values() for clip in clips.values())}))
