"""Shared "help" output for the hand-run test / give / dev commands (README: 명령 도움말). Importing it has no side effects.

A command that takes an id the user has to remember answers {<arg>:"help"} with a list instead of acting:

    $data modify storage rlk:tmp hq set value "$(id)"
    execute if data storage rlk:tmp {hq:"help"} run return run function <its help list>

(check_lines()). A macro function is instantiated as a whole, so every line of it must still parse with "help" in the
argument: a line that needs a number there (scoreboard players set ... $(id)) moves to a <cmd>_do function that the
command calls after the check ($function ..._do {id:$(id)} parses with id = help).

The list is one header line and one line per value, "id — 한국어 이름"; clicking a line suggests the full command. Every
component is plain text whose root is an empty text without style, so nothing inherits a colour, bold or a glyph font.
The runtime lists (items, characters, engravings, elements) use the same format through F:help/row.

Chapter mobs (rlk:cm/test {t}): cm/test_help is generated by cm_test_help() from CM_C1 (the hand-written chapter-1
mobs) plus one line `function rlk:cm/c<N>/test_help` for every chapter section file found on disk. A chapter mob
generator writes its section with cm_test_section(N, rows) as cm/c<N>/test_help (inside its own cm/c<N>/ folder, so its
stale cleanup covers it) and calls cm_test_help(<fn root>) after writing its files. The result depends only on the files
on disk, so the chapter generators may run in any order, any number of times.
"""
from pathlib import Path

HQ = 'rlk:tmp'          # storage of the check (key hq)


def _dq(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def _sq(s):
    return "'" + str(s).replace('\\', '\\\\').replace("'", "\\'") + "'"


def check_lines(arg, help_fn):
    """The two first lines of a command: {<arg>:"help"} runs help_fn (a function id without rlk:) and returns."""
    return [f'$data modify storage {HQ} hq set value "$({arg})"',
            f'execute if data storage {HQ} {{hq:"help"}} run return run function rlk:{help_fn}']


def _plain(s):
    if any(c in str(s) for c in '"\'\\'):
        raise ValueError('help text with a quote or backslash (it is a macro argument of F:help/head · sub): ' + str(s))
    return str(s)


def head(cmd, what):
    """Header line (F:help/head, shared with the runtime lists): the command as typed (its argument shown as …) and
    what the list holds."""
    return f'function rlk:help/head {{cmd:"{_plain(cmd)}",what:"{_plain(what)}"}}'


def sub(title):
    """Group line inside a list (a chapter, a rarity, a phase): F:help/sub."""
    return f'function rlk:help/sub {{title:"{_plain(title)}"}}'


def note(text):
    return f'tellraw @s ["",{{text:{_dq(" " + text)},color:"gray"}}]'


def row(cmd, vid, name):
    """One value: '  <vid> — <name>', the whole line suggests cmd (the full command)."""
    return (f'tellraw @s [{{text:"",click_event:{{action:"suggest_command",command:{_sq(cmd)}}},'
            f'hover_event:{{action:"show_text",value:{_sq(cmd)}}}}},{{text:{_dq("  " + str(vid))},color:"yellow"}},'
            f'{{text:" — ",color:"dark_gray"}},{{text:{_dq(name)},color:"white"}}]')


# ---------------------------------------------------------------- rlk:cm/test {t:"help"}
CM_TEST = '/function rlk:cm/test {t:"%s"}'
# chapter-1 mobs (hand-written cm/<id>/**, cm/spawn/<id>)
CM_C1 = [('sw', '검사'), ('ar', '궁수'), ('fm', '불 마법사'), ('im', '얼음 마법사'), ('sh', '방패병'), ('cn', '대포병')]
CM_SECTION = 'cm/c{n}/test_help'


def cm_test_section(chapter, rows):
    """Text of cm/c<chapter>/test_help: a chapter line and one line per (id, name)."""
    return '\n'.join([f'# GENERATED: {chapter}챕터 시험 소환 id (cm/test {{t:"help"}} → cm/test_help, tools/help_lib.py)',
                      sub(f'{chapter}챕터')] + [row(CM_TEST % i, i, n) for i, n in rows]) + '\n'


def cm_test_help(fn_root):
    """(Re)write cm/test_help from CM_C1 and the chapter sections on disk. Returns True when the file changed."""
    fn_root = Path(fn_root)
    cm = fn_root / 'cm'
    chapters = sorted(int(p.name[1:]) for p in cm.glob('c[0-9]*') if p.name[1:].isdigit()
                      and (p / 'test_help.mcfunction').is_file())
    lines = ['# GENERATED by tools/help_lib.py cm_test_help() (called by every chapter mob generator) - do not edit.',
             '# /function rlk:cm/test {t:"help"} (= rlk:cm {t:"help"}): the test-spawn ids. Chapter 1 is help_lib.CM_C1;',
             '# chapter N adds cm/cN/test_help (help_lib.cm_test_section) and calls cm_test_help() again.',
             head('/function rlk:cm/test {t:…}', '시험 소환 id (바라보는 쪽 5칸 앞, 1레벨)'),
             sub('1챕터')] + [row(CM_TEST % i, i, n) for i, n in CM_C1]
    lines += [f'function rlk:{CM_SECTION.format(n=n)}' for n in chapters]
    text = '\n'.join(lines) + '\n'
    p = fn_root / 'cm/test_help.mcfunction'
    if p.is_file() and p.read_text(encoding='utf-8') == text:
        return False
    p.write_text(text, encoding='utf-8')
    return True
