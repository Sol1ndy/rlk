def render(s, comp_text):
    """Plain text of a tellraw / title component list as the game shows it: text components verbatim, nbt components
    from storage (interpret:true reads the stored component's text)."""
    out = []
    for m in re.finditer(r'\{(text|nbt):"((?:[^"\\]|\\.)*)"(,storage:"([^"]+)")?(,interpret:true)?', comp_text):
        kind, val, _x, st, interp = m.groups()
        if kind == 'text':
            out.append(val)
        else:
            try:
                v = s.path_get(s.storage[st], val)
            except (KeyError, IndexError, TypeError):
                v = ''
            if interp and isinstance(v, dict):
                v = v.get('text', '')
            out.append(str(v))
    return ''.join(out)


