def sec_pack():
    rc, probs, last = run_pack(DP)
    check('P1 check_mboss_pack on the tree: exit 0, 0 problems', rc == 0 and not probs and last.endswith('0 problem(s).'), (rc, probs, last))
    v = variant('spproto_fn')
    rc, probs, last = run_pack(v)
    check('P2 spproto with rwHook true but no mboss/spproto/reward: the missing hook (+ the sp/reward line naming it)', rc == 1
          and probs[0] == 'spproto: missing hook mboss/spproto/reward' and len(probs) == 2
          and re.fullmatch(r'mboss/sp/reward:\d+ missing function rlk:mboss/spproto/reward', probs[1]), probs)
    hook = v / 'data/rlk/function/mboss/spproto/reward.mcfunction'
    hook.write_text('# test hook\nscoreboard players add #HOOK azs 1\n', encoding='utf-8')
    rc, probs, last = run_pack(v)
    check('P3 with a (non-macro) hook file: 0 problems', rc == 0 and not probs, probs)
    hook.write_text('$say $(id)\n', encoding='utf-8')
    rc, probs, last = run_pack(v)
    check('P4 a macro hook is refused', rc == 1 and probs == ['mboss/spproto/reward: should not be a macro function'], probs)
    hook.write_text('scoreboard players add #HOOK azs 1\n', encoding='utf-8')
    rw = v / 'data/rlk/function/mboss/sp/reward.mcfunction'
    t = rw.read_text(encoding='utf-8')
    hl = 'execute if data storage rlk:mboss cur{id:"spproto"} as @a[tag=player,limit=1] run function rlk:mboss/spproto/reward\n'
    rw.write_text(t.replace(hl, ''), encoding='utf-8')
    rc, probs, last = run_pack(v)
    check('P5 the hook line missing from sp/reward is reported', rc == 1 and len(probs) == 1 and 'F:mboss/sp/reward' in probs[0], probs)
    rw.write_text(t.replace(hl, hl + hl), encoding='utf-8')
    rc, probs, last = run_pack(v)
    check('P6 a doubled hook line is reported', rc == 1 and any('F:mboss/sp/reward' in p for p in probs), probs)
    rw.write_text(t, encoding='utf-8')
    bh = v / 'data/rlk/function/mboss/bars_hide.mcfunction'
    tb = bh.read_text(encoding='utf-8')
    bh.write_text(tb + 'scoreboard players set #mbBarOff mb 1\n', encoding='utf-8')
    rc, probs, last = run_pack(v)
    check('P7 bars_hide setting the flag is reported (FN-f: only the wrappers may)', rc == 1
          and any('mboss/bars_hide' in p and '#mbBarOff' in p for p in probs), probs)
    bh.write_text(tb, encoding='utf-8')
    rg = v / 'data/rlk/function/mboss/register.mcfunction'
    tr = rg.read_text(encoding='utf-8')
    rg.write_text(tr.replace(',poof:0b', ''), encoding='utf-8')
    rc, probs, last = run_pack(v)
    check('P8 a record without the poof:0b its entry asks for is reported', rc == 1
          and any('spproto record poof:0b' in p for p in probs), probs)
    rg.write_text(tr, encoding='utf-8')
    rc, probs, last = run_pack(v)
    check('P9 restored: 0 problems again', rc == 0 and not probs, probs)
    drop('spproto_fn')


