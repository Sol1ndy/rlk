"""Narukami (Raiden) uninstall: remove everything the boss created (review RD-S1, S3-F).

    python3 tools/build_raiden_uninstall.py

Writes data/rlk/function/boss/raiden/uninstall.mcfunction from what the generated boss/raiden and room/raiden
functions create, so it stays complete when a generator adds an objective: every `scoreboard objectives add`, every
`bossbar add` and the boss storage rlk:rd. It runs last in build_raiden_all.py (after every other Raiden generator).
The engine's rlk:uninstall calls rlk:boss/raiden/cleanup; it should call rlk:boss/raiden/uninstall instead (one line
in the shared file, the lead's change), which runs the cleanup first.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FN = ROOT / 'data/rlk/function'
OUT = FN / 'boss/raiden/uninstall.mcfunction'
OBJ = re.compile(r'^\s*(?:execute .* run )?scoreboard objectives add (\S+)', re.M)
BAR = re.compile(r'^\s*(?:execute .* run )?bossbar add (\S+)', re.M)
STO = re.compile(r'storage rlk:rd ([A-Za-z_][A-Za-z0-9_]*)')


def scan():
    objs, bars, keys = set(), set(), set()
    for d in (FN / 'boss/raiden', FN / 'room/raiden'):
        for p in sorted(d.rglob('*.mcfunction')):
            if p == OUT:
                continue
            t = p.read_text(encoding='utf-8')
            objs.update(OBJ.findall(t))
            bars.update(BAR.findall(t))
            keys.update(STO.findall(t))
    return sorted(objs), sorted(bars), sorted(keys)


def main():
    objs, bars, keys = scan()
    assert 'rd' in objs and 'rlk:narukami' in bars, 'boss/raiden/init not generated yet (run build_raiden_all.py)'
    lines = ['# Generated by tools/build_raiden_uninstall.py (do not edit). From rlk:uninstall: the fight cleanup, then every',
             f'# scoreboard objective ({len(objs)}), boss bar ({len(bars)}) and storage key (rlk:rd: {len(keys)}) the boss created.',
             'function rlk:boss/raiden/cleanup',
             'kill @e[tag=rlk_raiden_part]',
             'kill @e[tag=rlk_raiden]',
             # the arena backdrop job and the vortex spin stop on their own, but not before the objectives go
             'schedule clear rlk:room/raiden/bg/tick',
             'schedule clear rlk:room/raiden/bg/spin']
    lines += [f'bossbar remove {b}' for b in bars]
    lines += [f'data remove storage rlk:rd {k}' for k in keys]
    lines += [f'scoreboard objectives remove {o}' for o in objs if o != 'rd'] + ['scoreboard objectives remove rd']
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Generated boss/raiden/uninstall: {len(objs)} objectives, {len(bars)} boss bars, {len(keys)} storage keys of rlk:rd.')


if __name__ == '__main__':
    main()
